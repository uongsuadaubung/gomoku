/**
 * Lấy ngẫu nhiên câu thoại và thế các biến ngữ cảnh vào chuỗi
 */
export function getTutorDialogue(
  event: TutorDialogueEvent,
  context?: TutorDialogueContext
): string {
  const list = TUTOR_DIALOGUES[event] || ['Hãy tập trung và quan sát kỹ bàn cờ nhé!'];
  const template = list[Math.floor(Math.random() * list.length)];

  return template
    .replace('{coord}', context?.coord || '')
    .replace('{coordAI}', context?.coordAI || '')
    .replace('{botName}', context?.botName || '')
    .replace('{level}', String(context?.level || ''))
    .replace('{nextLevel}', String(context?.nextLevel || ''));
}
